"""Generate wonik_hall.world: a simple test hall modelled on the T-Robotics/Wonik test site photos
(walls with window bands and steel columns, benches and cabinets along the walls) plus a central
island so that the route around it is a U (ㄷ) shape. All primitives; one static model.

usage: python3 make_hall_world.py ../worlds/wonik_hall.world
"""
import sys

# Hall interior [m] in the world frame; the robot spawns at the origin facing +x.
X0, X1, Y0, Y1 = -2.0, 14.0, -2.0, 8.0
WALL_T, WALL_H = 0.2, 2.5
COLUMN = 0.4          # steel column cross-section, on the inner face of the long walls
COLUMN_PITCH = 4.0

parts = []  # (name, x, y, z_bottom, sx, sy, sz, material, collide)


def box(name, x, y, sx, sy, sz, material, z0=0.0, collide=True):
    parts.append((name, x, y, z0, sx, sy, sz, material, collide))


# walls
cx, cy, lx, ly = (X0 + X1) / 2, (Y0 + Y1) / 2, X1 - X0, Y1 - Y0
box("wall_south", cx, Y0 - WALL_T / 2, lx + 2 * WALL_T, WALL_T, WALL_H, "Gazebo/White")
box("wall_north", cx, Y1 + WALL_T / 2, lx + 2 * WALL_T, WALL_T, WALL_H, "Gazebo/White")
box("wall_west", X0 - WALL_T / 2, cy, WALL_T, ly, WALL_H, "Gazebo/White")
box("wall_east", X1 + WALL_T / 2, cy, WALL_T, ly, WALL_H, "Gazebo/White")

# window bands (visual only, slightly proud of the wall) between the columns of the long walls
xs = [X0 + COLUMN_PITCH * k for k in range(int((X1 - X0) / COLUMN_PITCH) + 1)]
for i in range(len(xs) - 1):
    mid, w = (xs[i] + xs[i + 1]) / 2, COLUMN_PITCH - 1.0
    box(f"window_s{i}", mid, Y0 + 0.01, w, 0.02, 1.0, "Gazebo/BlueGlow", z0=1.2, collide=False)
    box(f"window_n{i}", mid, Y1 - 0.01, w, 0.02, 1.0, "Gazebo/BlueGlow", z0=1.2, collide=False)

# steel columns on the inner face of the long walls
for i, x in enumerate(xs[1:-1]):
    box(f"column_s{i}", x, Y0 + COLUMN / 2, COLUMN, COLUMN, WALL_H, "Gazebo/DarkGrey")
    box(f"column_n{i}", x, Y1 - COLUMN / 2, COLUMN, COLUMN, WALL_H, "Gazebo/DarkGrey")

# central island: workbenches + shelving, so the route around it is a U (ㄷ)
box("island_shelf", 6.0, 3.0, 8.0, 0.6, 1.6, "Gazebo/Wood")
box("island_bench_a", 3.5, 3.0 - 0.7, 3.0, 0.8, 0.9, "Gazebo/White")
box("island_bench_b", 8.5, 3.0 + 0.7, 3.0, 0.8, 0.9, "Gazebo/White")

# along the walls (as in the photos): benches on the west wall, cabinets and a charger box on the
# north wall, a cone near the east wall
box("bench_west", X0 + 0.5, 3.0, 0.8, 1.8, 0.9, "Gazebo/White")
box("cabinet_n0", 1.0, Y1 - 0.5, 0.6, 0.6, 1.0, "Gazebo/White")
box("cabinet_n1", 1.7, Y1 - 0.5, 0.6, 0.6, 1.0, "Gazebo/White")
box("charger_box", 9.5, Y1 - 0.45, 0.8, 0.5, 0.7, "Gazebo/White")
box("crate_se", 12.6, Y0 + 0.6, 1.0, 0.8, 0.8, "Gazebo/Blue")


def link_xml(p):
    name, x, y, z0, sx, sy, sz, mat, collide = p
    pose = f"{x:.3f} {y:.3f} {z0 + sz / 2:.3f} 0 0 0"
    geom = f"<geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>"
    col = f"""
        <collision name="{name}_collision">
          <pose>{pose}</pose>
          {geom}
        </collision>""" if collide else ""
    return f"""{col}
        <visual name="{name}_visual">
          <pose>{pose}</pose>
          {geom}
          <material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>{mat}</name></script></material>
        </visual>"""


cones = "".join(f"""
    <include>
      <name>cone_{i}</name>
      <uri>model://construction_cone</uri>
      <pose>{x} {y} 0 0 0 0</pose>
    </include>""" for i, (x, y) in enumerate([(13.4, 7.4), (-1.5, -1.5)]))

world = f"""<?xml version="1.0"?>
<!-- Wonik test hall ({X1 - X0:.0f} m x {Y1 - Y0:.0f} m), modelled on the test-site photos in 티로보틱스_QD.pptx.
     Generated by wonik_gazebo/scripts/make_hall_world.py; primitives only. The robot spawns at the origin facing +x; the
     U (ㄷ) route around the central island is (0,0) -> (12,0) -> (12,6) -> (0,6). -->
<sdf version="1.6">
  <world name="default">
    <include><uri>model://ground_plane</uri></include>
    <include><uri>model://sun</uri></include>
    <physics name="default_physics" default="0" type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
      <real_time_update_rate>1000</real_time_update_rate>
    </physics>
    <scene>
      <shadows>false</shadows>
    </scene>

    <model name="hall">
      <static>true</static>
      <link name="link">{"".join(link_xml(p) for p in parts)}
      </link>
    </model>
{cones}
  </world>
</sdf>
"""
with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write(world)
print(f"{len(parts)} boxes -> {sys.argv[1]}")
